package com.example.xssscanner.storage

import com.example.xssscanner.BuildConfig
import com.example.xssscanner.domain.model.XssFinding
import javax.inject.Inject

/**
 * Implements §10's xss_report.html minimum contents: target summary, URL/
 * param/finding-per-severity counts, finding list with evidence+payload,
 * and GENERIC mitigation text only — never a target-specific claim without
 * evidence.
 */
class HtmlReportExporter @Inject constructor() {

    fun buildReport(scanSessionId: String, findings: List<XssFinding>): String {
        val bySeverityCount = findings.groupingBy { severityOf(it.riskScore) }.eachCount()
        val rows = findings.joinToString("\n") { f ->
            """
            <tr>
              <td>${escape(f.url)}</td>
              <td>${escape(f.parameter)}</td>
              <td>${escape(f.status.name)}</td>
              <td>${f.riskScore}</td>
              <td><pre>${escape(f.payload)}</pre></td>
              <td><pre>${escape(f.evidence)}</pre></td>
            </tr>
            """.trimIndent()
        }

        return """
        <!DOCTYPE html>
        <html lang="en">
        <head><meta charset="utf-8"><title>XSS Scan Report</title></head>
        <body>
          <h1>XSS Scan Report</h1>
          <p>Scan session: ${escape(scanSessionId)}</p>
          <p>Generated by XSS Scanner v${BuildConfig.VERSION_NAME}</p>
          <h2>Summary</h2>
          <ul>
            <li>Total findings: ${findings.size}</li>
            ${bySeverityCount.entries.joinToString("\n") { "<li>${it.key}: ${it.value}</li>" }}
          </ul>
          <h2>Findings</h2>
          <table border="1" cellpadding="4">
            <tr><th>URL</th><th>Parameter</th><th>Status</th><th>Risk</th><th>Payload</th><th>Evidence</th></tr>
            $rows
          </table>
          <h2>General Mitigation Recommendations</h2>
          <ul>
            <li>Apply context-aware output encoding at every reflection point (HTML, attribute, JS, URL, CSS).</li>
            <li>Adopt a strict Content-Security-Policy to reduce the impact of any missed encoding gap.</li>
            <li>Sanitize any HTML that must be rendered as markup using a vetted sanitizer allow-list.</li>
            <li>Prefer safe DOM APIs (textContent, setAttribute with validated values) over innerHTML/outerHTML/document.write with unvalidated input.</li>
          </ul>
          <p><em>These are generic recommendations; verify applicability to each specific finding before remediation.</em></p>
        </body>
        </html>
        """.trimIndent()
    }

    private fun severityOf(score: Int): String = when {
        score >= 80 -> "Critical"
        score >= 60 -> "High"
        score >= 30 -> "Medium"
        score > 0 -> "Low"
        else -> "Info"
    }

    private fun escape(value: String): String = value
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
}
